import {execFileSync,spawnSync} from 'node:child_process';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
const git=(...args)=>execFileSync('git',args,{encoding:'utf8'}).trim();
const [tag,sha,...reasonParts]=process.argv.slice(2);
const reason=reasonParts.join(' ').trim();
const version=JSON.parse(readFileSync('functions-monitoring/package.json','utf8')).version;
if(tag!==`monitoring/v${version}`||!/^[a-f0-9]{40}$/.test(sha??'')||!reason)throw new Error('Usage: node functions-monitoring/deploy.mjs monitoring/vVERSION MAIN_SHA REASON');
if(git('rev-parse','HEAD')!==sha||git('rev-parse',`${tag}^{commit}`)!==sha)throw new Error('Fixed tag/source mismatch');
git('merge-base','--is-ancestor',sha,'origin/main');
if(git('status','--porcelain'))throw new Error('Deployment requires a clean worktree');
const config=JSON.parse(readFileSync('firebase.monitoring.json','utf8'));
if(Object.keys(config).join(',')!=='functions'||config.functions.length!==1||config.functions[0].source!=='functions-monitoring'||config.functions[0].codebase!=='class-monitoring')throw new Error('Unexpected deployment scope');
const receipt={project:'cloud-board-stationd',tag,sourceSha:sha,scope:'functions:class-monitoring',reason,startedAt:new Date().toISOString(),status:'started'};
mkdirSync('build/monitoring',{recursive:true});
const save=()=>writeFileSync('build/monitoring/release.json',JSON.stringify(receipt,null,2)+'\n');save();
const result=spawnSync('firebase',['deploy','--project',receipt.project,'--config','firebase.monitoring.json','--only',receipt.scope,'--non-interactive'],{stdio:'inherit'});
receipt.status=result.status===0?'deployed':'failed';receipt.finishedAt=new Date().toISOString();save();
process.exitCode=result.status??1;
