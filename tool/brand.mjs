import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {renderPlatformOutputs} from './brand-platforms.mjs';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const displayKeys = ['name', 'nameKo', 'defaultWorkoutBrand', 'defaultStoreName'];
const platformKeys = ['iosDisplayName', 'iosBundleName', 'iosActivityDisplayName',
  'androidDisplayName', 'webTitle', 'webName', 'webShortName', 'macosDisplayName',
  'windowsDisplayName', 'linuxDisplayName'];
const linkKeys = ['service', 'privacy', 'terms', 'support', 'accountDeletion', 'supportEmail'];

function keys(value, expected, label) {
  if (!value || typeof value !== 'object' || Array.isArray(value) ||
      JSON.stringify(Object.keys(value).sort()) !== JSON.stringify([...expected].sort())) {
    throw new Error(`${label}: expected only ${expected.join(', ')}`);
  }
}

export function validateBrand(config) {
  keys(config, ['schemaVersion', 'display', 'platforms', 'links'], 'brand');
  if (config.schemaVersion !== 1) throw new Error('Unsupported brand schemaVersion');
  for (const [name, fields] of [['display', displayKeys], ['platforms', platformKeys], ['links', linkKeys]]) {
    keys(config[name], fields, name);
    for (const field of fields) {
      const value = config[name][field];
      if (typeof value !== 'string' || !value.trim() || value !== value.trim() || /[\u0000-\u001f\u007f]/u.test(value)) {
        throw new Error(`${name}.${field}: a nonempty, single-line string is required`);
      }
    }
  }
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(config.links.supportEmail)) {
    throw new Error('links.supportEmail: invalid email');
  }
  for (const field of linkKeys.filter(key => key !== 'supportEmail')) {
    const url = new URL(config.links[field]);
    if (!(url.protocol === 'https:' || (field === 'support' && url.protocol === 'mailto:')) || url.username || url.password) {
      throw new Error(`links.${field}: expected public HTTPS link or support mailto`);
    }
  }
  return config;
}

export function dartString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;
}

function dartClass(name, values) {
  // Formatter directives keep generated output deterministic without requiring
  // a local Dart SDK when preparing native/server branding outputs.
  return `// Generated by node tool/brand.mjs from config/brand.json. Do not edit.\n` +
    `// dart format off\n\nabstract final class ${name} {\n` +
    Object.entries(values).map(([key, value]) => `  static const ${key} = ${dartString(value)};\n`).join('') +
    '}\n';
}

export function brandOutputs(root, input) {
  const config = validateBrand(input);
  const outputs = new Map([
    ['lib/src/app/core/config/app_brand.dart', dartClass('AppBrand', config.display)],
    ['lib/src/app/core/config/app_links.dart', dartClass('AppLinks', config.links)],
  ]);
  const platform = renderPlatformOutputs(config, file => fs.readFileSync(path.join(root, file), 'utf8'));
  for (const [file, text] of platform) {
    if (outputs.has(file) || path.isAbsolute(file) || file.split(/[\\/]/).includes('..')) {
      throw new Error(`Invalid generated output: ${file}`);
    }
    outputs.set(file, text);
  }
  return outputs;
}

export function generateBrand(root, config, {check = false} = {}) {
  const outputs = brandOutputs(root, config);
  const changed = [];
  for (const [file, contents] of outputs) {
    const target = path.join(root, file);
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === contents) continue;
    changed.push(file);
    if (!check) {
      fs.mkdirSync(path.dirname(target), {recursive: true});
      fs.writeFileSync(target, contents);
    }
  }
  if (check && changed.length) throw new Error(`Brand outputs are stale:\n${changed.join('\n')}\nRun node tool/brand.mjs`);
  return {outputs: [...outputs.keys()], changed};
}

function sourceFiles(root, folder) {
  const base = path.join(root, folder);
  if (!fs.existsSync(base)) return [];
  return fs.readdirSync(base, {withFileTypes: true}).flatMap(entry => {
    const file = path.posix.join(folder, entry.name);
    if (entry.isDirectory()) return ['.git', 'build', 'node_modules', '.dart_tool', 'Pods', '.symlinks', 'ephemeral'].includes(entry.name) ? [] : sourceFiles(root, file);
    return /\.(dart|js|swift|kt|java|cc|cpp|h|xml|plist|html|json|rc)$/.test(entry.name) ? [file] : [];
  });
}

export function checkBrandHardcoding(root, generatedPaths, config) {
  const allowlist = JSON.parse(fs.readFileSync(path.join(root, 'config/brand-hardcoding-allowlist.json'), 'utf8'));
  config ??= JSON.parse(fs.readFileSync(path.join(root, 'config/brand.json'), 'utf8'));
  const terms = [...new Set(['CloudBoard', 'Cloud Board', '클라우드보드',
    ...Object.values(config.display), ...Object.values(config.links)])];
  const escapedTerms = terms.map(term => term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  const brand = new RegExp(escapedTerms.join('|'), 'u');
  // Consume comments and complete strings together so comment markers inside a
  // string remain data. Triple quotes/templates may span multiple lines.
  const codeTokens = /\/\/[^\n]*|\/\*[\s\S]*?\*\/|('''|"""|['"`])((?:\\[\s\S]|(?!\1)[^\\])*)\1/gu;
  const attribute = /(['"])((?:\\[\s\S]|(?!\1)[^\\])*)\1/gu;
  // Quoted attributes can contain '>'; text nodes need no surrounding quotes.
  const markupTokens = /<!--[\s\S]*?-->|<(?:"[^"]*"|'[^']*'|[^'">])*?>|([^<]+)/gu;
  const generated = new Set(generatedPaths);
  const failures = [];
  const seen = new Map();
  let maskedPlatformOutputs;
  for (const file of ['lib', 'functions/src', 'ios', 'android/app/src', 'macos/Runner', 'windows/runner', 'linux/runner', 'web'].flatMap(folder => sourceFiles(root, folder))) {
    // Existing DTO generator output and compatibility fixtures are deliberately
    // distinct from product display code. AppBrand output is checked separately.
    if (/\.(g|freezed)\.dart$/.test(file)) continue;
    let source = fs.readFileSync(path.join(root, file), 'utf8');
    if (generated.has(file)) {
      if (source.includes('Generated by node tool/brand.mjs from config/brand.json. Do not edit.') ||
          source.includes('Generated from config/brand.json by tool/brand.mjs. Do not edit.')) continue;
      // plist/web files are only partially generated. Mask precisely the owned
      // fields through the same renderer, leaving all other content inspectable.
      maskedPlatformOutputs ??= renderPlatformOutputs({
        ...config,
        platforms: Object.fromEntries(Object.keys(config.platforms).map(key => [key, ''])),
      }, file => fs.readFileSync(path.join(root, file), 'utf8'));
      source = maskedPlatformOutputs.get(file) ?? source;
    }
    function inspect(value, offset) {
      const brandOffset = value.search(brand);
      if (brandOffset < 0) return;
      const allowed = allowlist.find(entry => entry.file === file && entry.text === value);
      if (!allowed) {
        const line = source.slice(0, offset + brandOffset).split('\n').length;
        failures.push(`${file}:${line}: ${value}`);
      } else {
        const key = `${file}\u0000${value}`;
        seen.set(key, (seen.get(key) ?? 0) + 1);
      }
    }
    if (/\.(xml|plist|html)$/.test(file)) {
      for (const token of source.matchAll(markupTokens)) {
        if (token[0].startsWith('<!--')) continue;
        if (token[1] !== undefined) inspect(token[1], token.index);
        else for (const match of token[0].matchAll(attribute)) {
          inspect(match[2], token.index + match.index + match[1].length);
        }
      }
    } else {
      for (const match of source.matchAll(codeTokens)) {
        if (match[1] !== undefined) inspect(match[2], match.index + match[1].length);
      }
    }
  }
  for (const entry of allowlist) {
    const count = seen.get(`${entry.file}\u0000${entry.text}`) ?? 0;
    if (!entry.reason || count !== entry.occurrences) failures.push(`Stale/invalid brand exception: ${entry.file} (${count}/${entry.occurrences})`);
  }
  if (failures.length) throw new Error(`Hardcoded product display text:\n${failures.join('\n')}`);
}

export function checkTechnicalContracts(root) {
  const contracts = JSON.parse(fs.readFileSync(path.join(root, 'config/brand-technical-contracts.json'), 'utf8'));
  for (const contract of contracts) {
    const source = fs.readFileSync(path.join(root, contract.file), 'utf8');
    const actual = [...source.matchAll(new RegExp(contract.pattern, contract.flags))].map(match => match[0]).sort();
    if (JSON.stringify(actual) !== JSON.stringify(contract.expected)) {
      throw new Error(`Technical brand contract changed: ${contract.file}. Product display configuration must not rename identifiers.`);
    }
  }
}

export function main(args = process.argv.slice(2)) {
  let root = repositoryRoot;
  let configPath;
  let check = false;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check') check = true;
    else if (args[i] === '--root' && args[i + 1]) root = path.resolve(args[++i]);
    else if (args[i] === '--config' && args[i + 1]) configPath = path.resolve(args[++i]);
    else throw new Error(`Unknown argument: ${args[i]}`);
  }
  const config = JSON.parse(fs.readFileSync(configPath ?? path.join(root, 'config/brand.json'), 'utf8'));
  const result = generateBrand(root, config, {check});
  if (check) {
    checkBrandHardcoding(root, result.outputs, config);
    checkTechnicalContracts(root);
  }
  console.log(`Brand ${check ? 'verified' : 'generated'}: ${result.outputs.length} outputs, ${result.changed.length} changes`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
